l("");
l("  const [phase,    setPhase]    = useState<Phase>('LOADING');");
l("  const [event,    setEvent]    = useState<EventData | null>(null);");
l("  const [name,     setName]     = useState('');");
l("  const [email,    setEmail]    = useState('');");
l("  const [nameErr,  setNameErr]  = useState('');");
l("  const [emailErr, setEmailErr] = useState('');");
l("  const [apiAlert, setApiAlert] = useState('');   // 429 inline alert");
l("  const [errorMsg, setErrorMsg] = useState('');   // ERROR phase message");
l("  const [pollTick, setPollTick] = useState(0);   // drives progress bar");
l("  const pollingRef = useRef<ReturnType<typeof setInterval> | null>(null);");
l("  const userIdRef  = useRef('');");
l("");
l("  // Fetch event details on mount");
l("  useEffect(() => {");
l("    if (!eventId) { setPhase('NOT_FOUND'); return; }");
l("    fetch(`/api/events/${eventId}`)");
l("      .then(r => r.ok ? r.json() : Promise.reject(new Error('not-found')))");
l("      .then((data: EventData) => { setEvent(data); setPhase('IDLE'); })");
l("      .catch(() => setPhase('NOT_FOUND'));");
l("  }, [eventId]);");
l("");
l("  // Cleanup polling on unmount");
l("  useEffect(() => () => { if (pollingRef.current) clearInterval(pollingRef.current); }, []);");
l("");
l("  // ── Validation ────────────────────────────────────────────────────────────");
l("  function validate(): boolean {");
l("    let ok = true;");
l("    if (!name.trim()) { setNameErr('Full name is required.'); ok = false; } else setNameErr('');");
l("    if (!email.trim()) { setEmailErr('Email address is required.'); ok = false; }");
l("    else if (!/^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/.test(email.trim())) { setEmailErr('Please enter a valid email address.'); ok = false; }");
l("    else setEmailErr('');");
l("    return ok;");
l("  }");
l("");
l("  // ── Submit ────────────────────────────────────────────────────────────────");
l("  async function handleSubmit(e: React.FormEvent) {");
l("    e.preventDefault();");
l("    if (!validate()) return;");
l("    setApiAlert('');");
l("    setPhase('SUBMITTING');");
l("    try {");
l("      // Step 1: Resolve a stable userId from the email");
l("      const uRes = await fetch('/api/users/find-or-create', {");
l("        method: 'POST',");
l("        headers: { 'Content-Type': 'application/json' },");
l("        body: JSON.stringify({ name: name.trim(), email: email.trim() }),");
l("      });");
l("      if (!uRes.ok) throw new Error('Unable to set up your account. Please try again.');");
l("      const { userId } = await uRes.json() as { userId: string };");
l("      userIdRef.current = userId;");
l("");
l("      // Step 2: Enqueue the registration");
l("      const rRes = await fetch('/api/registrations', {");
l("        method: 'POST',");
l("        headers: { 'Content-Type': 'application/json' },");
l("        body: JSON.stringify({ userId, eventId }),");
l("      });");
l("");
l("      if (rRes.status === 429) {");
l("        setPhase('IDLE');");
l("        setApiAlert(\"You're clicking too fast! Please wait a moment and try again.\");");
l("        return;");
l("      }");
l("      if (rRes.status === 202) {");
l("        setPhase('WAITING');");
l("        startPolling(userId);");
l("        return;");
l("      }");
l("      if (!rRes.ok) {");
l("        const d = await rRes.json().catch(() => ({})) as { error?: string };");
l("        throw new Error(d.error ?? 'Registration failed. Please try again.');");
l("      }");
l("    } catch (err) {");
l("      setPhase('ERROR');");
l("      setErrorMsg(err instanceof Error ? err.message : 'An unexpected error occurred. Please try again.');");
l("    }");
l("  }");
l("");
l("  // ── Polling ───────────────────────────────────────────────────────────────");
l("  function startPolling(uid: string) {");
l("    const t0 = Date.now();");
l("    setPollTick(0);");
l("    pollingRef.current = setInterval(async () => {");
l("      const elapsed = Date.now() - t0;");
l("      setPollTick(tick => tick + 1);");
l("      if (elapsed > 15_000) {");
l("        clearInterval(pollingRef.current!);");
l("        pollingRef.current = null;");
l("        setPhase('TIMEOUT');");
l("        return;");
l("      }");
l("      try {");
l("        const r = await fetch(`/api/registrations/status?userId=${uid}&eventId=${eventId}`);");
